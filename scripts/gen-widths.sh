#!/bin/sh
# Regenerates internal/vt/widths_table.go from the pinned utf8proc (the version
# scripts/build-tmux.sh links into the reference tmux), so that the engine's
# widths are tmux's. Needs a C compiler.
set -eu
UTF8PROC_VERSION=2.12.0
UTF8PROC_SHA256=f564011d38b2888d583d510b08e69ffa15aa117155db1b9b49ef1dfe1fa25111
UTF8PROC_URL="https://github.com/JuliaStrings/utf8proc/archive/refs/tags/v$UTF8PROC_VERSION.tar.gz"

root=$(cd "$(dirname "$0")/.." && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
curl -sSLf -o "$work/u.tar.gz" "$UTF8PROC_URL"
if command -v sha256sum >/dev/null; then sum=$(sha256sum "$work/u.tar.gz" | cut -d' ' -f1); else sum=$(shasum -a 256 "$work/u.tar.gz" | cut -d' ' -f1); fi
if [ "$sum" != "$UTF8PROC_SHA256" ]; then
	echo "gen-widths: SHA-256 mismatch: got $sum, want $UTF8PROC_SHA256" >&2
	exit 1
fi
tar -xzf "$work/u.tar.gz" -C "$work"
u="$work/utf8proc-$UTF8PROC_VERSION"
cc -O2 -DUTF8PROC_STATIC -I"$u" -o "$work/widths" "$root/scripts/gen-widths/widths.c" "$u/utf8proc.c"
"$work/widths" >"$work/widths.txt"
header=$(head -1 "$work/widths.txt" | sed 's/^# //')
out="$root/internal/vt/widths_table.go"
{
	echo "// Code generated by scripts/gen-widths.sh; DO NOT EDIT."
	echo
	echo "package vt"
	echo
	echo "// widthRanges are the code points whose width is not 1, from $header:"
	echo "// utf8proc_charwidth, with private use characters 1, as tmux uses it. They are sorted."
	echo "var widthRanges = []widthRange{"
	tail -n +2 "$work/widths.txt" | while read -r a b w; do
		printf '\t{0x%s, 0x%s, %s},\n' "$a" "$b" "$w"
	done
	echo "}"
} >"$out"
gofmt -w "$out"
echo "gen-widths: $(tail -n +2 "$work/widths.txt" | wc -l | tr -d ' ') ranges, $header → $out"
