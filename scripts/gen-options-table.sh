#!/bin/sh
# Regenerates internal/options/table_gen.go, tmux's option table (names, types, scopes, flags,
# limits, choices and defaults), from a tmux source tree (the pinned version's release tarball,
# unpacked). The table is read by compiling tmux's own options-table.c with a small program
# that prints it, so every default is exactly tmux's.
#
#   scripts/gen-options-table.sh <tmux source dir>
#
# Needs what building tmux needs (scripts/build-tmux.sh): a C compiler, libevent and ncurses.
set -eu
src=$(cd "$1" && pwd)
root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/internal/options/table_gen.go"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

cp -R "$src" "$work/src"
(cd "$work/src" && ./configure >"$work/configure.log" 2>&1) || {
	cat "$work/configure.log" >&2
	exit 1
}
# The feature macros only: the package strings hold quotes the shell would split.
defs=$(sed -n 's/^DEFS = //p' "$work/src/Makefile" | tr ' ' '\n' | grep -E '^-D(HAVE_|_)' | tr '\n' ' ')
# The defaults Makefile.am passes in AM_CPPFLAGS (default-terminal, lock-command, mouse), with
# what configure found for them.
term=$(sed -n 's/^DEFAULT_TERM = //p' "$work/src/Makefile")
lock=$(sed -n 's/^DEFAULT_LOCK_CMD = //p' "$work/src/Makefile")

cat >"$work/gen.c" <<'C'
#include <stdio.h>
#include <string.h>

#include "tmux.h"

extern const struct options_table_entry options_table[];
extern const struct options_name_map options_other_names[];

/* Go-quotes a string. */
static void
q(const char *s)
{
	const unsigned char *p;

	putchar('"');
	for (p = (const unsigned char *)s; *p != '\0'; p++) {
		if (*p == '"' || *p == '\\')
			printf("\\%c", *p);
		else if (*p < 0x20 || *p == 0x7f)
			printf("\\x%02x", *p);
		else
			putchar(*p);
	}
	putchar('"');
}

static void
list(const char **l)
{
	printf("[]string{");
	for (; *l != NULL; l++) {
		q(*l);
		if (l[1] != NULL)
			printf(", ");
	}
	printf("}");
}

int
main(void)
{
	const struct options_table_entry *oe;
	const struct options_name_map *map;
	static const char *types[] = { "TypeString", "TypeNumber", "TypeKey", "TypeColour",
	    "TypeFlag", "TypeChoice", "TypeCommand" };

	printf("var Table = []Entry{\n");
	for (oe = options_table; oe->name != NULL; oe++) {
		printf("\t{Name: ");
		q(oe->name);
		if (oe->alternative_name != NULL) {
			printf(", Alternative: ");
			q(oe->alternative_name);
		}
		printf(", Type: %s, Scope: %d, Flags: %d", types[oe->type], oe->scope, oe->flags);
		if (oe->minimum != 0 || oe->maximum != 0)
			printf(", Minimum: %u, Maximum: %u", oe->minimum, oe->maximum);
		if (oe->choices != NULL) {
			printf(", Choices: ");
			list(oe->choices);
		}
		if (oe->default_str != NULL) {
			printf(", DefaultStr: ");
			q(oe->default_str);
		}
		if (oe->default_num != 0)
			printf(", DefaultNum: %lld", oe->default_num);
		if (oe->default_arr != NULL) {
			printf(", DefaultArr: ");
			list(oe->default_arr);
		}
		if (oe->separator != NULL) {
			printf(", HasSeparator: true, Separator: ");
			q(oe->separator);
		}
		if (oe->pattern != NULL) {
			printf(", Pattern: ");
			q(oe->pattern);
		}
		if (oe->unit != NULL) {
			printf(", Unit: ");
			q(oe->unit);
		}
		printf("},\n");
	}
	printf("}\n\n");
	printf("// OtherNames are names tmux takes for options (options_other_names).\n");
	printf("var OtherNames = map[string]string{\n");
	for (map = options_other_names; map->from != NULL; map++) {
		printf("\t");
		q(map->from);
		printf(": ");
		q(map->to);
		printf(",\n");
	}
	printf("}\n");
	return (0);
}
C

# shellcheck disable=SC2086 # DEFS is a list of -D flags.
cc $defs -DTMUX_TERM="\"$term\"" -DTMUX_LOCK_CMD="\"$lock\"" -DTMUX_MOUSE=1 -I"$work/src" -I"$work/src/compat" $(pkg-config --cflags libevent 2>/dev/null) \
	-o "$work/gen" "$work/gen.c" "$work/src/options-table.c" \
	-Wl,--unresolved-symbols=ignore-all 2>"$work/cc.log" || {
	cat "$work/cc.log" >&2
	exit 1
}

ver=$(sed -n 's/^AC_INIT(\[tmux\], *\([^]]*\)).*/\1/p' "$src/configure.ac")
{
	cat <<GO
// Code generated by scripts/gen-options-table.sh from tmux $ver; DO NOT EDIT.

// The table below is read from tmux's options-table.c:
//
