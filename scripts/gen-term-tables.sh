#!/bin/sh
# Regenerates internal/termout/tables_gen.go: terminfo's standard capability names, in the order
# compiled terminfo files store them (read from ncurses' boolnames, numnames and strnames, so it
# needs a C compiler and ncurses), and tmux's table of the capabilities it uses (tty-term.c):
#
#   scripts/gen-term-tables.sh <tmux source dir>
set -eu
src=$1
root=$(cd "$(dirname "$0")/.." && pwd)
ver=$(sed -n 's/^AC_INIT(\[tmux\], *\([^]]*\)).*/\1/p' "$src/configure.ac")
out="$root/internal/termout/tables_gen.go"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

cat >"$tmp/capnames.c" <<'C'
#include <stdio.h>
#include <term.h>
int main(void) {
	int i;
	for (i = 0; boolnames[i] != NULL; i++) printf("bool %s\n", boolnames[i]);
	for (i = 0; numnames[i] != NULL; i++) printf("num %s\n", numnames[i]);
	for (i = 0; strnames[i] != NULL; i++) printf("str %s\n", strnames[i]);
	return 0;
}
C
cc -o "$tmp/capnames" "$tmp/capnames.c" -lncurses
"$tmp/capnames" >"$tmp/names"

list() {
	awk -v k="$1" '$1 == k { printf "\t\"%s\",\n", $2 }' "$tmp/names"
}

{
	cat <<HEAD
// Code generated by scripts/gen-term-tables.sh from ncurses and tmux $ver; DO NOT EDIT.

package termout

// The standard terminfo capability names, in the order compiled terminfo files store their
// values (ncurses' boolnames, numnames and strnames; the names are X/Open's).
var (
	terminfoBools = []string{
$(list bool)
	}
	terminfoNums = []string{
$(list num)
	}
	terminfoStrings = []string{
$(list str)
	}
)

// The capabilities tmux uses, in its order (tmux.h's enum tty_code_code, tty-term.c's
// tty_term_codes; ISC license,
// Copyright (c) 2008 Nicholas Marriott <nicholas.marriott@gmail.com>).
var codes = []codeEntry{
HEAD
	# tty_term_codes is indexed by tmux.h's enum tty_code_code, which sets the order.
	sed -n '/^static const struct tty_term_code_entry tty_term_codes\[\] = {/,/^};/p' "$src/tty-term.c" |
		sed -n 's/.*\[TTYC_\([A-Z0-9_]*\)\] = *{ TTYCODE_\([A-Z]*\), "\([^"]*\)" }.*/\1 \2 \3/p' >"$tmp/codes"
	sed -n '/^enum tty_code_code {/,/^};/p' "$src/tmux.h" | grep -oE 'TTYC_[A-Z0-9_]+' | sed 's/^TTYC_//' |
		while read -r c; do
			awk -v c="$c" '$1 == c { t = ($2 == "STRING" ? "codeString" : ($2 == "NUMBER" ? "codeNumber" : "codeFlag"));
				printf "\t{%s, \"%s\"},\n", t, $3 }' "$tmp/codes"
		done
	echo "}"
} >"$out"
gofmt -w "$out"
