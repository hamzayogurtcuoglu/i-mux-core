#!/bin/sh
# Regenerates internal/commands/table_gen.go, tmux's command table (names, aliases, argument
# templates and bounds, usages, which commands start a server), from a tmux source tree (the pinned
# version's release tarball, unpacked):
#
#   scripts/gen-command-table.sh <tmux source dir>
set -eu
src=$1
root=$(cd "$(dirname "$0")/.." && pwd)
ver=$(sed -n 's/^AC_INIT(\[tmux\], *\([^]]*\)).*/\1/p' "$src/configure.ac")
out="$root/internal/commands/table_gen.go"

# The usage macros, as NAME<tab>"value" lines.
macros=$(sed -n 's/^#define \(CMD_[A-Z_]*_USAGE\) \(".*"\)$/\1	\2/p' "$src/tmux.h")

# Every entry, one tab-separated line: its C variable, name, alias, template, bounds, whether it
# starts a server, and its usage (string literals and macros joined).
entries=$(echo "$macros" | awk -v OFS='\t' '
FILENAME == "-" { split($0, kv, "\t"); macro[kv[1]] = kv[2]; next }
/^const struct cmd_entry cmd_[a-z_]+_entry = \{/ {
	v = $4; name = ""; alias = ""; tmpl = ""; lo = ""; hi = ""; start = 0; usage = ""
	flags = ""; source = "-"; target = "-"
	inside = 1; inusage = 0; inflags = 0; next
}
inside && inflags {
	f = f " " $0
	if ($0 ~ /,[ \t]*$/) { inflags = 0; flags = cflags(f) }
	next
}
inside && inusage {
	u = u " " $0
	if ($0 ~ /,[ \t]*$/) { inusage = 0; usage = join(u) }
	next
}
inside && /\.name = "/ { name = $0; sub(/.*\.name = "/, "", name); sub(/".*/, "", name) }
inside && /\.alias = / {
	alias = $0; sub(/.*\.alias = /, "", alias); sub(/,.*/, "", alias)
	if (alias == "NULL") alias = ""; else gsub(/"/, "", alias)
}
inside && /\.args = \{/ {
	a = $0; sub(/.*\.args = \{ */, "", a)
	tmpl = a; sub(/^"/, "", tmpl); sub(/".*/, "", tmpl)
	sub(/^"[^"]*", */, "", a); split(a, b, /, */); lo = b[1]; hi = b[2]
}
inside && /\.usage = / {
	u = $0; sub(/.*\.usage = /, "", u)
	if (u ~ /,[ \t]*$/) usage = join(u); else inusage = 1
}
inside && /\.flags = / {
	f = $0; sub(/.*\.flags = /, "", f)
	if (f ~ /,[ \t]*$/) flags = cflags(f); else inflags = 1
}
inside && /\.source = / { source = find($0) }
inside && /\.target = / { target = find($0) }
inside && /^};/ {
	start = (flags ~ /CmdStartserver/)
	print v, name, alias, tmpl, lo, hi, start, usage, (flags == "" ? "0" : flags), source, target
	inside = 0
}
# cflags turns "CMD_A|CMD_B," into Go constants.
function cflags(text,    n, parts, i, out, w) {
	gsub(/[ \t,]/, "", text)
	if (text == "0") return "0"
	n = split(text, parts, "|")
	out = ""
	for (i = 1; i <= n; i++) {
		w = gocase(parts[i])
		out = out (out == "" ? "" : "|") w
	}
	return out
}
# find turns "{ 't', CMD_FIND_PANE, CMD_FIND_CANFAIL }," into a Go Find.
function find(text,    a, parts, fl) {
	a = text; sub(/.*\{ */, "", a); sub(/ *\}.*/, "", a)
	split(a, parts, / *, */)
	fl = parts[3]
	if (fl == "0") fl = "0"; else fl = cflags(fl)
	return "&TargetSpec{Flag: " parts[1] ", Type: " gocase(parts[2]) ", Flags: " fl "}"
}
# gocase turns CMD_FIND_WINDOW_INDEX into FindWindowIndex and CMD_AFTERHOOK into CmdAfterhook.
function gocase(w,    n, parts, i, out) {
	sub(/^CMD_FIND_/, "Find_", w)
	n = split(tolower(w), parts, "_")
	out = ""
	for (i = 1; i <= n; i++)
		out = out toupper(substr(parts[i], 1, 1)) substr(parts[i], 2)
	return out
}
# join concatenates C string literals and usage macros.
function join(text,    out, t) {
	for (m in macro) gsub(m, macro[m], text)
	out = ""
	while (match(text, /"[^"]*"/)) {
		t = substr(text, RSTART + 1, RLENGTH - 2)
		out = out t
		text = substr(text, RSTART + RLENGTH)
	}
	return out
}' - "$src"/cmd-*.c)

{
	cat <<HEAD
