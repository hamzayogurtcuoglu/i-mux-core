// Command parity turns the go test -json output of i-mux's e2e suite run on imux-core into
// PARITY.md (TASKS.md C6.2): a table of every test with its status and, for failures, a cause
// and the task that fixes it. The causes come from a notes file, one line per test,
// "TestName | cause | task", or per kind of failure, "~ text | cause | task" for every failure
// whose output holds text; a failure without a note gets its first error line.
//
//	go run ./cmd/parity [-commit c] [-notes parity/notes.txt] e2e.json > PARITY.md
package main

import (
	"bufio"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"os"
	"sort"
	"strings"
)

type event struct {
	Action  string
	Package string
	Test    string
	Output  string
	Elapsed float64
}

type result struct {
	status string // pass, fail, skip, or "" while it runs
	output []string
	secs   float64
}

type note struct{ cause, task string }

// notes are the notes file's lines: by test, and by text in a failure's output.
type notes struct {
	byTest map[string]note
	byText []struct {
		text string
		note
	}
}

// find is the note for a test: its own, else the first whose text its output holds.
func (ns notes) find(name string, out []string) note {
	if n, ok := ns.byTest[name]; ok {
		return n
	}
	all := strings.Join(out, "")
	for _, t := range ns.byText {
		if strings.Contains(all, t.text) {
			return t.note
		}
	}
	return note{}
}

func main() {
	commit := flag.String("commit", "unknown", "the i-mux commit the suite ran at")
	notesPath := flag.String("notes", "", "the notes file (TestName | cause | task)")
	flag.Parse()
	if flag.NArg() != 1 {
		fmt.Fprintln(os.Stderr, "usage: parity [-commit c] [-notes file] e2e.json")
		os.Exit(2)
	}
	f, err := os.Open(flag.Arg(0))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()
	results, err := read(f)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	ns := notes{byTest: map[string]note{}}
	if *notesPath != "" {
		if ns, err = readNotes(*notesPath); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
	write(os.Stdout, *commit, results, ns)
}

// read collects each top-level test's status and output.
func read(r io.Reader) (map[string]*result, error) {
	results := map[string]*result{}
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 1<<20), 16<<20)
	for sc.Scan() {
		var e event
		if err := json.Unmarshal(sc.Bytes(), &e); err != nil || e.Test == "" {
			continue
		}
		name := e.Test
		if i := strings.IndexByte(name, '/'); i >= 0 {
			name = name[:i]
		}
		res := results[name]
		if res == nil {
			res = &result{}
			results[name] = res
		}
		switch e.Action {
		case "output":
			res.output = append(res.output, e.Output)
		case "pass", "fail", "skip":
			if e.Test == name {
				res.status, res.secs = e.Action, e.Elapsed
			}
		}
	}
	return results, sc.Err()
}

func readNotes(path string) (notes, error) {
	ns := notes{byTest: map[string]note{}}
	b, err := os.ReadFile(path)
	if err != nil {
		return ns, err
	}
	for _, line := range strings.Split(string(b), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		parts := strings.Split(line, "|")
		for i := range parts {
			parts[i] = strings.TrimSpace(parts[i])
		}
		for len(parts) < 3 {
			parts = append(parts, "")
		}
		n := note{cause: parts[1], task: parts[2]}
		if text, ok := strings.CutPrefix(parts[0], "~"); ok {
			ns.byText = append(ns.byText, struct {
				text string
				note
			}{strings.TrimSpace(text), n})
			continue
		}
		ns.byTest[parts[0]] = n
	}
	return ns, nil
}

// firstError is a failed test's first line that reads as an error.
func firstError(out []string) string {
	for _, l := range out {
		t := strings.TrimSpace(l)
		if strings.Contains(t, "_test.go:") {
			if _, rest, ok := strings.Cut(t, ": "); ok {
				t = rest
			}
			if len(t) > 140 {
				t = t[:140] + "…"
			}
			return t
		}
	}
	return ""
}

func cell(s string) string { return strings.ReplaceAll(strings.ReplaceAll(s, "|", `\|`), "\n", " ") }

func write(w io.Writer, commit string, results map[string]*result, ns notes) {
	names := make([]string, 0, len(results))
	count := map[string]int{}
	for n, r := range results {
		names = append(names, n)
		st := r.status
		if st == "" {
			st = "unfinished"
		}
		count[st]++
	}
	sort.Strings(names)
	fmt.Fprintln(w, "# Parity with tmux: i-mux's e2e suite on i-mux-core")
	fmt.Fprintln(w)
	fmt.Fprintf(w, "Generated by `scripts/imux-e2e.sh` (TASKS.md C6.2) from i-mux at `%s`. ", commit)
	fmt.Fprintln(w, "Causes and tasks come from `parity/notes.txt`; a failure with no note shows its first error.")
	fmt.Fprintln(w)
	fmt.Fprintf(w, "%d tests: %d pass, %d fail, %d skip", len(names), count["pass"], count["fail"], count["skip"])
	if count["unfinished"] > 0 {
		fmt.Fprintf(w, ", %d unfinished", count["unfinished"])
	}
	fmt.Fprintln(w, ".")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "| Test | Status | Cause | Task |")
	fmt.Fprintln(w, "| --- | --- | --- | --- |")
	for _, n := range names {
		r := results[n]
		st := r.status
		if st == "" {
			st = "unfinished"
		}
		var nt note
		if st != "pass" {
			nt = ns.find(n, r.output)
		}
		cause := nt.cause
		if cause == "" && st == "fail" {
			cause = firstError(r.output)
		}
		if st == "pass" {
			cause, nt.task = "", ""
		}
		fmt.Fprintf(w, "| `%s` | %s | %s | %s |\n", n, st, cell(cause), cell(nt.task))
	}
}
